"""Generate RESULTS.md from data/results/ (every headline number in the project).

    python scripts/make_results.py

Do not edit RESULTS.md by hand; rerun this script. The dynamics checks in section 1 are
recomputed here (a few seconds); everything else is read from the run_*.py outputs.
"""

from __future__ import annotations

import datetime as dt
import json
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from cr3bp import units  # noqa: E402
from cr3bp.dynamics import ATOL, METHOD, RTOL, jacobi, propagate  # noqa: E402
from cr3bp.jpl import FAMILIES, load_family, system  # noqa: E402
from cr3bp.lagrange import gradient_U, lagrange_points  # noqa: E402

RES = ROOT / "data" / "results"
PUB = json.loads((ROOT / "data" / "published" / "nrho_references.json").read_text())
FAM_TITLES = {"lyapunov_L1": "L1 Lyapunov", "lyapunov_L2": "L2 Lyapunov",
              "halo_L1_N": "L1 halo, northern", "halo_L1_S": "L1 halo, southern",
              "halo_L2_N": "L2 halo, northern", "halo_L2_S": "L2 halo, southern"}


def e(x, d=1):
    """Scientific notation like 2.4e-12."""
    return f"{x:.{d}e}".replace("e-0", "e-").replace("e+0", "e+")


def j(name):
    return json.loads((RES / f"{name}.json").read_text())


def dynamics_checks():
    mu = units.MU
    L = lagrange_points(mu)
    s = system()
    eq = max(np.max(np.abs(gradient_U(r, mu))) for r in L.values())
    vs_jpl = max(np.max(np.abs(L[k] - s[k])) for k in L)
    fam = load_family("halo_L2_S")
    i = len(fam) // 2
    X0, T = fam.states[i], fam.period[i]
    arc = propagate(X0, 10 * T, mu, t_eval=np.linspace(0, 10 * T, 2001))
    C = jacobi(arc.X, mu)
    return {"eq": eq, "vs_jpl": vs_jpl, "drift": float(np.max(np.abs(C - C[0]))),
            "drift_days": float(units.nd_to_days(10 * T)), "drift_C": float(C[0])}


def catalog_precision_l2():
    """Self-consistency of the JPL L2 Lyapunov entries nearest our five worst nu comparisons."""
    from cr3bp.stability import analyze

    d = np.load(RES / "lyapunov_L2.npz")
    cat = load_family("lyapunov_L2")
    err = np.abs(d["nu"] - d["nu_cat_lyapunov_L2"]) / d["nu_cat_lyapunov_L2"]
    worst = np.argsort(np.nan_to_num(err))[::-1][:5]
    clos, nus = [], []
    for i in worst:
        k = int(np.argmin(np.abs(cat.jacobi - d["C"][i])))
        a = analyze(cat.states[k], cat.period[k], units.MU, rtol=1e-13)
        clos.append(a["closure"])
        nus.append(abs(a["nu"] - cat.stability[k]) / cat.stability[k])
    rp = d["r_perilune"][worst] * units.LU_KM
    return {"rp_min": rp.min(), "rp_max": rp.max(), "clos_min": min(clos), "clos_max": max(clos),
            "nu_self_max": max(nus)}


def main():
    lines = []
    w = lines.append
    cat0 = load_family("halo_L2_S")
    w("# RESULTS")
    w("")
    w(f"*Generated by `scripts/make_results.py` on {dt.date.today().isoformat()}. "
      "Do not edit by hand.*")
    w("")
    w("All numbers below come from the code in this repository. Model: Earth-Moon circular "
      "restricted three-body problem (CR3BP), point-mass primaries, rotating frame.")
    w("")

    # ---- setup ----
    w("## 0. Constants, reference data and tolerances")
    w("")
    w("| Item | Value |")
    w("|---|---|")
    w(f"| Mass ratio μ (from JPL API) | {units.MU!r} |")
    w(f"| Length unit LU (from JPL API) | {units.LU_KM:.4f} km |")
    w(f"| Time unit TU (from JPL API) | {units.TU_S:.4f} s = {units.TU_DAYS:.6f} d |")
    w(f"| Lunar radius (from JPL API) | {units.R_MOON_KM} km |")
    w(f"| JPL catalog fetched (UTC) | {cat0.fetched_utc} |")
    counts = ", ".join(f"{FAM_TITLES[f].replace(', northern', ' N').replace(', southern', ' S')} "
                       f"{len(load_family(f))}" for f in FAMILIES)
    w(f"| Catalog orbits cached | {counts} |")
    w(f"| Integrator | `scipy.integrate.solve_ivp`, {METHOD} |")
    w(f"| Default tolerances | rtol = {e(RTOL, 0)}, atol = {e(ATOL, 0)} |")
    w(f"| Tightened tolerances | rtol = atol = 1e-13 for halo orbits passing within 0.05 LU "
      f"({0.05 * units.LU_KM:,.0f} km) of the Moon, for any orbit whose full-period closure exceeded 5e-11 at the "
      "default, and for all NRHO solutions |")
    w("| Newton convergence | ‖F‖ < 1e-12 on the half-period constraints, or a stalled residual "
      "below 1e-10 |")
    w("")

    # ---- milestone 1 ----
    d = dynamics_checks()
    w("## 1. Dynamics core")
    w("")
    w("| Check | Result |")
    w("|---|---|")
    w(f"| max \\|∇U\\| at L1-L5 (equilibrium residual) | {e(d['eq'])} |")
    w(f"| max difference of L1-L5 from JPL's tabulated positions | {e(d['vs_jpl'])} LU |")
    w(f"| Jacobi drift, JPL L2 halo propagated 10 periods ({d['drift_days']:.1f} d) | "
      f"{e(d['drift'])} |")
    w("| STM vs. central differences | agree to < 5e-8 (relative), difference falls as h², "
      "see `tests/test_dynamics.py` |")
    w("")

    # ---- stability index definition ----
    w("Stability index used throughout (matches the JPL catalog, checked in "
      "`tests/test_stability.py`): ν = ½(|λ_max| + 1/|λ_max|), λ_max the monodromy eigenvalue "
      "of largest modulus.")
    w("")

    # ---- milestones 2 and 3 ----
    w("## 2-3. Lyapunov and halo families vs. the JPL catalog")
    w("")
    w("Two comparisons for each family. **Interpolated:** the catalog's period and stability "
      "index are spline-interpolated at each computed orbit's Jacobi constant, within runs of "
      "the family where C is monotone. **Pointwise:** at 60 catalog orbits spread along the "
      "family, our orbit is corrected with one initial-condition coordinate fixed to the "
      "catalog value (no interpolation; valid at folds in C).")
    w("")
    w("### Family summary")
    w("")
    w("| Family | Members | C range | Period range [d] | Max closure ‖X(T)−X₀‖ | "
      "Max reciprocal-pair defect | Members at 1e-13 | Continuation |")
    w("|---|---|---|---|---|---|---|---|")
    total_members = 0
    for f in FAMILIES:
        s = j(f)
        total_members += s["members"]
        tight = s["rtol_counts"].get("1e-13", 0)
        meth = ", ".join(f"{v} {k}" for k, v in sorted(s["methods"].items()))
        w(f"| {FAM_TITLES[f]} | {s['members']} | {s['C_range'][0]:.4f} – {s['C_range'][1]:.4f} | "
          f"{units.nd_to_days(s['T_range'][0]):.3f} – {units.nd_to_days(s['T_range'][1]):.3f} | "
          f"{e(s['max_closure'])} | {e(s['max_pair_defect'])} | {tight} | {meth} |")
    w("")
    w(f"Total family members computed: **{total_members}** (southern halo branches are the "
      "northern ones mirrored z → −z and re-integrated).")
    w("")
    w("### Period and stability index vs. JPL")
    w("")
    w("| Family | Interp. n | Period rel. err. max / median | ν rel. err. max / median | "
      "Excl. folds: n, period max, ν max | Pointwise n (failed) | Pointwise period max | "
      "Pointwise C abs. max | Pointwise ν max |")
    w("|---|---|---|---|---|---|---|---|---|")
    pw_n = pw_Tmax = pw_Cmax = 0
    agg = {"pw_T": [], "pw_C": [], "pw_nu": []}
    for f in FAMILIES:
        c = j(f)["comparisons"][f]
        p = c["pointwise"]
        pw_n += p["n"]
        agg["pw_T"].append(p["T_relerr_max"])
        agg["pw_C"].append(p["C_abserr_max"])
        agg["pw_nu"].append(p["nu_relerr_max"])
        w(f"| {FAM_TITLES[f]} | {c['n_compared']} | {e(c['T_relerr_max'])} / "
          f"{e(c['T_relerr_median'])} | {e(c['nu_relerr_max'])} / {e(c['nu_relerr_median'])} | "
          f"{c['n_compared_excluding_folds']}, {e(c['T_relerr_max_excluding_folds'])}, "
          f"{e(c['nu_relerr_max_excluding_folds'])} | {p['n']} ({p['failed']}) | "
          f"{e(p['T_relerr_max'])} | {e(p['C_abserr_max'])} | {e(p['nu_relerr_max'])} |")
    w("")
    w(f"**Pointwise, all families: {pw_n} catalog orbits, period within "
      f"{e(max(agg['pw_T']))} (relative), Jacobi constant within {e(max(agg['pw_C']))}, "
      f"stability index within {e(max(agg['pw_nu']))} (relative), no failed corrections.**")
    w("")
    interp_n = sum(j(f)["comparisons"][f]["n_compared"] for f in FAMILIES)
    interp_med = max(j(f)["comparisons"][f]["T_relerr_median"] for f in FAMILIES)
    w(f"Interpolated, all families: {interp_n} comparisons; the median period error of every "
      f"family is ≤ {e(interp_med)}. The large interpolated maxima occur only within "
      "ΔC = 1e-4 of a fold in C (where dT/dC is unbounded and interpolating in C is "
      "ill-conditioned); the pointwise check covers the same regions without that problem.")
    w("")
    q = catalog_precision_l2()
    w(f"Where ν disagrees most (L2 Lyapunov), the five worst interpolated orbits pass "
      f"{q['rp_min']:.0f}–{q['rp_max']:.0f} km from the Moon's centre (inside the Moon). For the "
      f"nearest catalog entries, JPL's stored initial conditions close to only "
      f"{e(q['clos_min'])}–{e(q['clos_max'])} over one period, and JPL's tabulated ν differs by "
      f"up to {e(q['nu_self_max'])} (relative) from ν recomputed from JPL's own initial "
      "conditions. The catalog's precision, not the solver, limits the comparison there.")
    w("")
    w("### Bifurcations on the Lyapunov families (out-of-plane pair through +1, s_z = 2)")
    w("")
    w("| Family | C | Period [TU] | Period [d] | ν | Branches |")
    w("|---|---|---|---|---|---|")
    for f in ("lyapunov_L1", "lyapunov_L2"):
        for k, b in enumerate(j(f)["bifurcations"]):
            w(f"| {FAM_TITLES[f]} | {b['C']:.6f} | {b['T']:.6f} | "
              f"{units.nd_to_days(b['T']):.4f} | {b['nu']:.2f} | "
              f"{'halo (computed here)' if k == 0 else 'axial (not computed)'} |")
    h2 = load_family("halo_L2_N")
    h1 = load_family("halo_L1_N")
    b1 = j("lyapunov_L1")["bifurcations"][0]
    b2 = j("lyapunov_L2")["bifurcations"][0]
    w("")
    w(f"The JPL halo catalogs end at the planar family with periods {h1.period[np.argmax(h1.jacobi)]:.6f} "
      f"(L1, at C = {h1.jacobi.max():.6f}) and {h2.period.max():.6f} (L2); our bifurcating "
      f"orbits have {b1['T']:.6f} and {b2['T']:.6f}.")
    w("")

    # ---- Folta table 3 ----
    ft = j("folta_table3")
    w("### Cross-check: Folta et al. (2022), NASA/TP-20220014814, Table 3")
    w("")
    w("Our orbit corrected at each published period (starting from our family), compared with "
      "the published Jacobi constant and initial state (6 decimals in the table).")
    w("")
    w("| Family | Period [TU] | C published | C ours | Difference | Max state difference |")
    w("|---|---|---|---|---|---|")
    for r in ft["rows"]:
        w(f"| {FAM_TITLES[r['family']]} | {r['T_published']} | {r['C_published']:.6f} | "
          f"{r['C_ours']:.7f} | {r['C_diff']:+.1e} | {e(r['max_state_diff'])} |")
    w("")
    w(f"All six agree to within the table's rounding: max |ΔC| = "
      f"{e(max(abs(r['C_diff']) for r in ft['rows']))}, max state difference "
      f"{e(max(r['max_state_diff'] for r in ft['rows']))}.")
    w("")

    # ---- milestone 4 ----
    n = j("nrho")
    w("## 4. The 9:2 synodic-resonant L2 southern NRHO")
    w("")
    w(f"Target period (2/9) × {n['synodic_month_days']} d = "
      f"{2 / 9 * n['synodic_month_days']:.4f} d. The nondimensional period depends on the "
      "characteristic time, so the orbit is solved with two sets of constants. All values are "
      "CR3BP. Integration rtol = atol = 1e-13.")
    w("")
    w("| Quantity | JPL constants | Folta et al. (2022) Table 2 constants |")
    w("|---|---|---|")
    a, b = n["orbits"]["jpl"]["9:2"][0], n["orbits"]["folta"]["9:2"][0]
    ca, cb = n["orbits"]["jpl"]["constants"], n["orbits"]["folta"]["constants"]
    w(f"| μ, LU, TU | {ca['mu']:.12f}, {ca['LU_km']:.2f} km, {ca['TU_s']:.2f} s | "
      f"{cb['mu']:.12f}, {cb['LU_km']:.0f} km, {cb['TU_s']:.2f} s |")
    rows = [("Period [d]", "period_days", ".4f"), ("Period [TU]", "period_nd", ".6f"),
            ("Perilune radius [km]", "perilune_radius_km", ".1f"),
            ("Perilune altitude [km]", "perilune_altitude_km", ".1f"),
            ("Apolune radius [km]", "apolune_radius_km", ".1f"),
            ("Jacobi constant", "jacobi", ".6f"), ("Stability index ν", "stability_index", ".4f"),
            ("Closure ‖X(T)−X₀‖", "closure", ".1e")]
    for label, key, fmt in rows:
        w(f"| {label} | {format(a[key], fmt)} | {format(b[key], fmt)} |")
    w(f"| Initial state (apolune, nondim.) | {np.round(a['X0'], 10).tolist()} | "
      f"{np.round(b['X0'], 10).tolist()} |")
    w("")
    w(f"Perilune altitude uses the lunar radius {n['radius_moon_km']} km. Changing only the "
      f"characteristic quantities moves the 9:2 perilune by "
      f"{b['perilune_radius_km'] - a['perilune_radius_km']:.0f} km.")
    w("")
    z, le = PUB["zimovan2017"], PUB["lee2019"]
    w("### Comparison with published values")
    w("")
    w("| Source | Model | Published | Ours (JPL const.) | Ours (Folta const.) |")
    w("|---|---|---|---|---|")
    for res in ("9:2", "4:1", "3:1"):
        oa = n["orbits"]["jpl"][res][0]["perilune_radius_km"]
        ob = n["orbits"]["folta"][res][0]["perilune_radius_km"]
        pub = z["perilune_radius_km"][res]
        w(f"| Zimovan, Howell & Davis (2017), {res} perilune radius | CR3BP, read from a figure "
          f"(\"about\") | ~{pub} km | {oa:.0f} km ({oa - pub:+.0f}) | {ob:.0f} km ({ob - pub:+.0f}) |")
    w(f"| Lee (2019), 9:2 perilune radius | ephemeris, 15-yr reference trajectory | "
      f"{le['perilune_radius_km']['min']}–{le['perilune_radius_km']['max']} km, mean "
      f"{le['perilune_radius_km']['mean']} km | {a['perilune_radius_km']:.0f} km | "
      f"{b['perilune_radius_km']:.0f} km |")
    w(f"| Lee (2019), mean period | ephemeris | {le['period_days_mean']} d | "
      f"{a['period_days']:.3f} d (imposed) | {b['period_days']:.3f} d (imposed) |")
    w("")
    w("Folta et al. (2022) does not tabulate the 9:2 NRHO; it supplies the constants and the "
      "Table 3 check above. No published CR3BP apolune radius, Jacobi constant or stability "
      "index for the 9:2 NRHO was found in these sources, so those values are reported without "
      "comparison. CR3BP and ephemeris values are not expected to agree exactly.")
    w("")

    # ---- milestone 5 ----
    m = j("manifolds")
    w("## 5. Invariant manifolds")
    w("")
    w(f"L1 and L2 Lyapunov orbits at C = {m['C']}; {m['n_seeds']} seeds per manifold, step "
      f"d = {m['d_km']:.0f} km along the eigenvector (position part normalised), section "
      f"x = 1 − μ, y < 0, arcs up to {m['t_max_days']:.1f} d, stopped at the lunar or Earth "
      "surface.")
    w("")
    w("| Orbit | Period [d] | ν | Closure |")
    w("|---|---|---|---|")
    for k, o in m["orbits"].items():
        w(f"| {k} Lyapunov | {o['T_days']:.4f} | {o['nu']:.1f} | {e(o['closure'])} |")
    w("")
    w("| Manifold | Eigenvalue | Reached section | Lunar impacts | Jacobi drift max / median | "
      "Jacobi offset from step (max) |")
    w("|---|---|---|---|---|---|")
    for k, bdict in m["branches"].items():
        w(f"| {k.replace('_', ' ')} | {bdict['eigenvalue']:.6g} | {bdict['section_points']} | "
          f"{bdict['impacts']['moon']} | {e(bdict['jacobi_drift_max'])} / "
          f"{e(bdict['jacobi_drift_median'])} | {e(bdict['jacobi_step_offset_max'])} |")
    w("")
    w("The Jacobi offset introduced by the step is second order in d (the eigenvectors are "
      "tangent to the constant-C surface); the drift column is integration error.")
    w("")
    w("**Step-size sensitivity.** Distance from each section point to the d = 50 km section "
      "curve (y in km, ẏ in m/s):")
    w("")
    w("| d [km] | L1 unstable: Δy median / p95 [km] | Δẏ p95 [m/s] | "
      "L2 stable: Δy median / p95 [km] | Δẏ p95 [m/s] |")
    w("|---|---|---|---|---|")
    st = m["step_size_study"]
    worst = 0.0
    for dk in st["L1_unstable"]:
        if dk == str(int(m["d_km"])):
            continue
        r1, r2 = st["L1_unstable"][dk], st["L2_stable"][dk]
        worst = max(worst, r1["dy_km_p95"], r2["dy_km_p95"])
        w(f"| {dk} | {r1['dy_km_median']:.2f} / {r1['dy_km_p95']:.2f} | {r1['dvy_mps_p95']:.4f} | "
          f"{r2['dy_km_median']:.2f} / {r2['dy_km_p95']:.2f} | {r2['dvy_mps_p95']:.4f} |")
    ds = sorted(int(k) for k in st["L1_unstable"])
    w("")
    w(f"Over d = {ds[0]}–{ds[-1]} km the section curves agree to ≤ {worst:.1f} km (p95), the "
      "same order as the spacing of the sampled curve, so the results are insensitive to the "
      "step size in this range.")
    w("")
    h = m["heteroclinic"]
    if h.get("found"):
        w("**Heteroclinic connection (L1 → L2 Lyapunov, stretch goal).** Refined over the two "
          "manifold phases so that y and ẏ match at the section:")
        w("")
        w("| Quantity | Value |")
        w("|---|---|")
        w(f"| Phases on L1 / L2 orbit (fraction of period) | {h['tau_L1']:.6f} / {h['tau_L2']:.6f} |")
        w(f"| Section crossing y | {h['section_state'][1] * units.LU_KM:.1f} km |")
        w(f"| Position mismatch at section | {e(h['position_mismatch_km'])} km |")
        w(f"| Velocity mismatch at section | {h['velocity_mismatch_mms']:.3f} mm/s |")
        w(f"| Time L1 orbit (+{m['d_km']:.0f} km) → section | {h['time_L1_to_section_days']:.2f} d |")
        w(f"| Time section → L2 orbit (+{m['d_km']:.0f} km) | {h['time_section_to_L2_days']:.2f} d |")
        w("")
        w("The velocity mismatch comes from the two sides' slightly different Jacobi constants "
          "after the step (second-order offset, above).")
        w("")
    (ROOT / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("wrote RESULTS.md")


if __name__ == "__main__":
    main()
