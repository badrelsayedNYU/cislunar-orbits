"""Milestone 5: invariant manifolds of Lyapunov orbits."""

import json
import pathlib

import numpy as np
import pytest

from cr3bp.correction import V_from_state, correct, jacobi_constraint, state_from_V
from cr3bp.dynamics import jacobi, propagate
from cr3bp.lagrange import gradient_U
from cr3bp.manifolds import eigendirections, propagate_branch, seeds
from cr3bp.stability import monodromy
from cr3bp.units import LU_KM, MU

RESULTS = pathlib.Path(__file__).resolve().parents[1] / "data" / "results"


@pytest.fixture(scope="module")
def l1_orbit():
    d = np.load(RESULTS / "lyapunov_L1.npz")
    k = int(np.argmin(np.abs(d["C"] - 3.15)))
    c = correct(V_from_state(d["X0"][k], d["T"][k], True), MU, True,
                extra=jacobi_constraint(3.15, MU, True))
    return state_from_V(c.V, True), 2 * c.V[-1]


def grad_C(X):
    g = np.empty(6)
    g[:3] = 2 * gradient_U(X[:3], MU)
    g[3:] = -2 * X[3:]
    return g


def test_eigendirections(l1_orbit):
    X0, T = l1_orbit
    M, _ = monodromy(X0, T, MU)
    lu, vu, ls, vs = eigendirections(M)
    assert lu * ls == pytest.approx(1.0, rel=1e-6)
    assert lu > 100
    for lam, v in ((lu, vu), (ls, vs)):
        assert np.linalg.norm(v[:3]) == pytest.approx(1.0)
        np.testing.assert_allclose(M @ v, lam * v, atol=1e-8 * max(lam, 1))
        # an eigenvector with lambda != 1 is tangent to the Jacobi-constant surface
        assert abs(grad_C(X0) @ v) < 1e-7


def test_mapped_direction_is_eigenvector_at_every_phase(l1_orbit):
    X0, T = l1_orbit
    s = seeds(X0, T, MU, 8, "unstable")
    for k in (2, 5):
        Mk, _ = monodromy(s.X_orbit[k], T, MU)
        w = Mk @ s.v[k]
        np.testing.assert_allclose(w / np.linalg.norm(w[:3]), s.v[k], atol=1e-7)


def test_step_offset_in_jacobi_is_second_order(l1_orbit):
    X0, T = l1_orbit
    s = seeds(X0, T, MU, 4, "unstable")
    C0 = jacobi(s.X_orbit[1], MU)
    dC = [abs(jacobi(s.X_orbit[1] + d / LU_KM * s.v[1], MU) - C0) for d in (10.0, 20.0, 40.0)]
    assert dC[1] / dC[0] == pytest.approx(4, rel=0.05)
    assert dC[2] / dC[1] == pytest.approx(4, rel=0.05)


def test_unstable_departure_grows_by_lambda_per_period(l1_orbit):
    X0, T = l1_orbit
    s = seeds(X0, T, MU, 4, "unstable")
    d = 1.0 / LU_KM                                       # 1 km: linear regime for one period
    Xp = propagate(s.X_orbit[0] + d * s.v[0], T, MU).Xf
    sep = np.linalg.norm(Xp[:3] - X0[:3]) / d
    assert sep == pytest.approx(s.lam * np.linalg.norm((s.v[0])[:3]), rel=0.02)


def test_manifold_arcs_conserve_jacobi(l1_orbit):
    X0, T = l1_orbit
    s = seeds(X0, T, MU, 10, "unstable")
    for k in range(0, 10, 3):
        for sign in (+1, -1):
            a = propagate_branch(s.X_orbit[k] + sign * 50 / LU_KM * s.v[k], MU, backward=False,
                                 x_section=1 - MU, t_max=8.0)
            assert a.C_drift < 1e-10


def test_committed_manifold_results():
    """Checks on the numbers that RESULTS.md reports (generated by scripts/run_manifolds.py)."""
    m = json.loads((RESULTS / "manifolds.json").read_text())
    for b in m["branches"].values():
        assert b["jacobi_drift_max"] < 1e-10
        assert b["section_points"] > 100
    for name, rows in m["step_size_study"].items():
        for dk, r in rows.items():
            assert r["dy_km_p95"] < 10, (name, dk)
    h = m["heteroclinic"]
    assert h["found"]
    assert h["position_mismatch_km"] < 1e-3
    assert h["velocity_mismatch_mms"] < 1.0
